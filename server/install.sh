#!/usr/bin/env bash
# FS Music — one-step Invidious server installer
#
# Sets up Invidious + Invidious Companion + PostgreSQL with Docker, plus a free
# Cloudflare quick tunnel that gives the server an https:// address your phone
# can use. Made for Ubuntu on Oracle Cloud's Always Free tier (ARM or x86), but
# works on any Ubuntu/Debian machine.
#
#   curl -fsSL https://fairuzsamsuddin-code.github.io/fsmusic/server/install.sh | bash
#
# Safe to run again: it keeps your keys and only updates/restarts the services.
set -euo pipefail

DIR="$HOME/invidious"
BIN=/usr/local/bin

say()  { printf '\n\033[1;35m==> %s\033[0m\n' "$*"; }
warn() { printf '\n\033[1;33m!!  %s\033[0m\n' "$*"; }
die()  { printf '\n\033[1;31mxx  %s\033[0m\n' "$*"; exit 1; }

if [ "$(id -u)" -eq 0 ]; then SUDO=""; else SUDO="sudo"; fi
command -v apt-get >/dev/null || die "This installer needs Ubuntu or Debian."

# ---------------------------------------------------------------- packages
say "Installing Docker (takes 1–3 minutes on a new server)…"
APT="$SUDO apt-get -y -qq -o DPkg::Lock::Timeout=600"
for i in $(seq 1 20); do   # a brand-new server is often busy with its own first updates
  $APT update >/dev/null 2>&1 && break
  [ "$i" = 20 ] && die "Couldn't update packages. Run this command again in a few minutes."
  sleep 15
done
$APT install ca-certificates curl git openssl >/dev/null
if ! command -v docker >/dev/null; then
  for i in 1 2 3; do
    if curl -fsSL https://get.docker.com | $SUDO sh >/dev/null; then break; fi
    [ "$i" = 3 ] && die "Docker failed to install. Run this command again in a few minutes."
    warn "Docker install hit a snag (usually a background update). Retrying in 30s…"; sleep 30
  done
fi
$SUDO systemctl enable --now docker >/dev/null 2>&1 || true
[ -n "$SUDO" ] && $SUDO usermod -aG docker "$USER" 2>/dev/null || true
DC="$SUDO docker compose -f $DIR/docker-compose.yml"

# ---------------------------------------------------------------- invidious
say "Downloading Invidious…"
# The repo is needed for the database setup files (see docs.invidious.io/installation)
if [ -d "$DIR/.git" ]; then
  git -C "$DIR" pull -q --ff-only || warn "Couldn't update the Invidious files; using the existing copy."
else
  git clone -q --depth 1 https://github.com/iv-org/invidious.git "$DIR"
fi

KEYS="$DIR/.fsmusic-keys"
if [ ! -f "$KEYS" ]; then
  {
    echo "HMAC_KEY=$(openssl rand -hex 8)"
    echo "COMPANION_KEY=$(openssl rand -hex 8)"   # Companion needs exactly 16 characters
  } > "$KEYS"
  chmod 600 "$KEYS"
fi
# shellcheck disable=SC1090
. "$KEYS"

say "Writing the server configuration…"
cat > "$DIR/docker-compose.yml" <<EOF
# Generated by the FS Music installer. Based on the official production setup:
# https://docs.invidious.io/installation/#docker-compose-method-production
services:
  invidious:
    image: quay.io/invidious/invidious:latest
    restart: unless-stopped
    ports:
      - "127.0.0.1:3000:3000"
    environment:
      INVIDIOUS_CONFIG: |
        db:
          dbname: invidious
          user: kemal
          password: kemal
          host: invidious-db
          port: 5432
        check_tables: true
        invidious_companion:
        - private_url: "http://companion:8282/companion"
        invidious_companion_key: "${COMPANION_KEY}"
        hmac_key: "${HMAC_KEY}"
        registration_enabled: false
        captcha_enabled: false
    healthcheck:
      test: wget -nv --tries=1 --spider http://127.0.0.1:3000/api/v1/stats || exit 1
      interval: 30s
      timeout: 5s
      retries: 2
    logging:
      options:
        max-size: "50m"
        max-file: "3"
    depends_on:
      - invidious-db

  companion:
    image: quay.io/invidious/invidious-companion:latest
    environment:
      - SERVER_SECRET_KEY=${COMPANION_KEY}
    restart: unless-stopped
    logging:
      options:
        max-size: "50m"
        max-file: "3"
    cap_drop:
      - ALL
    read_only: true
    volumes:
      - companioncache:/var/tmp/youtubei.js:rw
    security_opt:
      - no-new-privileges:true

  invidious-db:
    image: docker.io/library/postgres:14
    restart: unless-stopped
    volumes:
      - postgresdata:/var/lib/postgresql/data
      - ./config/sql:/config/sql
      - ./docker/init-invidious-db.sh:/docker-entrypoint-initdb.d/init-invidious-db.sh
    environment:
      POSTGRES_DB: invidious
      POSTGRES_USER: kemal
      POSTGRES_PASSWORD: kemal
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U \$\$POSTGRES_USER -d \$\$POSTGRES_DB"]

  # Free https:// address for your phone (Cloudflare quick tunnel, no account needed).
  # The address changes if this container restarts; run "fsmusic-url" to see it.
  tunnel:
    image: cloudflare/cloudflared:latest
    restart: unless-stopped
    command: tunnel --no-autoupdate --url http://invidious:3000
    depends_on:
      - invidious

volumes:
  postgresdata:
  companioncache:
EOF

# ---------------------------------------------------------------- helper commands
say "Adding helper commands (fsmusic-url, fsmusic-update, fsmusic-logs)…"
$SUDO tee "$BIN/fsmusic-url" >/dev/null <<EOF
#!/usr/bin/env bash
# Prints the current https address of your server
$DC logs tunnel 2>/dev/null | grep -o 'https://[a-z0-9-]*\.trycloudflare\.com' | tail -1
EOF
$SUDO tee "$BIN/fsmusic-update" >/dev/null <<EOF
#!/usr/bin/env bash
# Updates Invidious & Companion (fixes most "YouTube changed something" breakages)
set -e
git -C "$DIR" pull -q --ff-only || true
$DC pull -q invidious companion invidious-db
$DC up -d invidious companion invidious-db
$SUDO docker image prune -f >/dev/null
echo "Updated. Your server address is unchanged: \$(fsmusic-url)"
EOF
$SUDO tee "$BIN/fsmusic-logs" >/dev/null <<EOF
#!/usr/bin/env bash
# Shows recent server logs (press Ctrl+C to stop following)
$DC logs --tail 60 -f invidious companion
EOF
$SUDO chmod +x "$BIN/fsmusic-url" "$BIN/fsmusic-update" "$BIN/fsmusic-logs"

# Weekly automatic update (Sunday 04:17) keeps up with YouTube changes
echo "17 4 * * 0 root $BIN/fsmusic-update >/var/log/fsmusic-update.log 2>&1" | $SUDO tee /etc/cron.d/fsmusic-update >/dev/null

# ---------------------------------------------------------------- start
say "Downloading and starting the server (2–5 minutes the first time)…"
$DC pull -q
$DC up -d

say "Waiting for Invidious to finish starting…"
ok=""
for _ in $(seq 1 60); do
  if curl -fsS -o /dev/null http://127.0.0.1:3000/api/v1/stats 2>/dev/null; then ok=1; break; fi
  sleep 5
done
[ -n "$ok" ] || die "Invidious didn't start. Run 'fsmusic-logs' to see why, or run this installer again."

URL=""
for _ in $(seq 1 30); do
  URL="$("$BIN/fsmusic-url" || true)"
  [ -n "$URL" ] && break
  sleep 3
done

say "Checking that YouTube answers this server…"
search_ok=""; video_ok=""
curl -fsS 'http://127.0.0.1:3000/api/v1/search?q=smashing+pumpkins+1979&type=video' 2>/dev/null | grep -q '"videoId"' && search_ok=1
for _ in 1 2 3; do   # Companion may need a moment to get its first YouTube session
  curl -fsS 'http://127.0.0.1:3000/api/v1/videos/4aeETEoNfOg' 2>/dev/null | grep -q '"adaptiveFormats":\[{' && { video_ok=1; break; }
  sleep 15
done

echo
echo "────────────────────────────────────────────────────────────"
if [ -n "$URL" ]; then
  printf '  \033[1;32mYour server is running!\033[0m\n\n'
  printf '  Server address (copy this into FS Music):\n\n'
  printf '      \033[1;36m%s\033[0m\n\n' "$URL"
else
  printf '  \033[1;33mThe server is running, but the tunnel address is not ready yet.\033[0m\n'
  printf '  Run  fsmusic-url  in a minute to get it.\n\n'
fi
[ -n "$search_ok" ] && echo "  ✔ YouTube search works" || echo "  ✘ YouTube search didn't answer yet"
[ -n "$video_ok" ]  && echo "  ✔ Song playback works" || {
  echo "  ✘ Song playback didn't work yet."
  echo "    Wait 5 minutes and try in the app. If it still fails, YouTube may be"
  echo "    blocking this server's IP address (common for cloud servers)."
}
echo
echo "  In FS Music: ☰ Settings → YouTube Servers → Add Custom Server"
echo "  → paste the address → choose Invidious → Add."
echo
echo "  Handy commands:  fsmusic-url · fsmusic-update · fsmusic-logs"
echo "────────────────────────────────────────────────────────────"
